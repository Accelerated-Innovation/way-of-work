"""§3 Commits: Conventional Commits, no vague summaries, work item referenced."""
from __future__ import annotations

import re

from ..util import Result, git

MERGE_OR_REVERT = re.compile(r"^(Merge (pull request|branch|remote-tracking branch)|Revert \")")


def header_regex(cfg: dict) -> re.Pattern:
    types = "|".join(map(re.escape, cfg["commits"]["types"]))
    return re.compile(rf"^(?P<type>{types})(?:\((?P<scope>[a-z0-9][a-z0-9._/-]*)\))?(?P<bang>!)?: (?P<summary>\S.*)$")


def _strip_comments(message: str) -> str:
    return "\n".join(l for l in message.splitlines() if not l.startswith("#")).strip()


def check_message(message: str, cfg: dict, label: str = "", require_ref: bool = False) -> Result:
    r = Result(f"Commit message{(' ' + label) if label else ''}")
    message = _strip_comments(message)
    if not message:
        r.error("Commit message is empty.")
        return r
    header = message.splitlines()[0].strip()
    if MERGE_OR_REVERT.match(header):
        r.note("Merge/revert commit generated by git; skipped.")
        return r

    m = header_regex(cfg).match(header)
    if not m:
        r.error(
            f"'{header}' is not Conventional Commits. Use type(scope): summary with type one of "
            f"{', '.join(cfg['commits']['types'])}. Example: fix(auth): expired sessions are logged out"
        )
        return r

    summary = m.group("summary").strip().rstrip(".").lower()
    if summary in cfg["commits"]["banned_summaries"] or re.fullmatch(r"(wip|tmp|temp)\b.*", summary):
        r.error(f"Summary '{m.group('summary')}' is too vague. Describe the behaviour that is now true.")
    if len(header) > cfg["commits"]["max_header_length"]:
        r.error(f"Header is {len(header)} characters; keep it under {cfg['commits']['max_header_length']}.")

    body = message[len(header):]
    if m.group("bang") and not re.search(r"(?im)^BREAKING[ -]CHANGE:", body):
        r.warn("Breaking change marked with '!'. Consider a 'BREAKING CHANGE:' footer explaining the impact.")

    if not re.search(cfg["work_item_pattern"], body) and not re.search(r"#\d+", body):
        msg = "No work item referenced in the body/footer (e.g. 'Refs: 1234')."
        (r.error if require_ref else r.warn)(msg)
    return r


def check_range(base: str, head: str, cfg: dict, cwd: str | None = None) -> Result:
    """Check every non-merge commit in base..head and fold into one result."""
    r = Result("Commit messages")
    raw = git("log", "--no-merges", "--format=%H%x1f%B%x1e", f"{base}..{head}", cwd=cwd)
    commits = [c.strip() for c in raw.split("\x1e") if c.strip()]
    if not commits:
        r.note("No new commits.")
        return r
    for entry in commits:
        sha, _, msg = entry.partition("\x1f")
        sub = check_message(msg, cfg)
        short = sha[:8]
        r.errors += [f"{short}: {e}" for e in sub.errors]
        r.warnings += [f"{short}: {w}" for w in sub.warnings]
    r.note(f"{len(commits)} commit(s) checked.")
    return r
